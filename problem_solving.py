def build_ic():
    rng = np.random.default_rng(seed)

    R   = sample_radii(N, rng)
    phi = rng.uniform(0.0, 2.0*np.pi, N)
    x   = R * np.cos(phi)
    y   = R * np.sin(phi)

    Meff = Mdisc_eff()
    m = np.full(N, Meff / N)

    vphi = v_phi(R)
    vx = -vphi * np.sin(phi)
    vy =  vphi * np.cos(phi)

    print(f"Profilo: {PROFILE.upper()}")
    print(f"  N = {N},  massa effettiva = {Meff:.4f} Msun  "
          f"(massa/particella = {m[0]:.3e})")

    pts = np.column_stack([x, y])
    tree = cKDTree(pts)
    d, _ = tree.query(pts, k=2)
    h_suggerita = 1.2 * np.median(d[:,1])
    print(f"  Distanza mediana al primo vicino = {np.median(d[:,1]):.2f} AU")
    print(f"  -> h iniziale suggerito = {h_suggerita:.2f} AU")

    return dict(x=x, y=y, vx=vx, vy=vy, m=m, R=R, phi=phi, vphi=vphi,
                h=h_suggerita)


