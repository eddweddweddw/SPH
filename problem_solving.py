# PARAMETRI COMUNI

Mstar   = 1.0          # massa stellare           [Msun]
Mdisc   = 0.1          # massa totale del disco   [Msun]
R_T     = 100.0        # raggio di norm. della T  [AU]
T100    = 20.0         # temperatura a R_T        [K]
q       = 0.23         # pendenza di T
mu      = 2.35         # peso molecolare medio
N       = 1000         # numero di particelle
seed    = 42

# parametri specifici del profilo LBP
Rin     = 50.0
Rout    = 600.0
Rc      = 150.0
gamma   = 1.0

# parametri specifici del profilo ad anello
R_ring  = 200.0        # centro dell'anello
DR_ring = 20.0         # semi-larghezza

G = 4.0 * np.pi**2
kB = 1.380649e-16; mp = 1.6726219e-24
AU = 1.495978707e13; YR = 3.15576e7
CMS_TO_AUYR = YR / AU


# CAMPI FISICI COMUNI

def sound_speed(R):
    T = T100 * (R / R_T)**(-q)
    cs_cgs = np.sqrt(kB * T / (mu * mp))
    return cs_cgs * CMS_TO_AUYR

def v_kepler(R):
    return np.sqrt(G * Mstar / R)


# PROFILO LBP

def surface_density_lbp(R):
    pref = Mdisc * (2.0 - gamma) / (2.0 * np.pi * Rc**2)
    return pref * (R / Rc)**(-gamma) * np.exp(-(R / Rc)**(2.0 - gamma))

def v_phi_lbp(R):
    cs2 = sound_speed(R)**2
    corr = cs2 * (1.0 + R / Rc + 2.0*q)
    v2 = v_kepler(R)**2 - corr
    if np.any(v2 <= 0):
        n_bad = np.sum(v2 <= 0)
        print(f"  ATTENZIONE: {n_bad} particelle con v_phi^2<=0; clip a 0.")
        v2 = np.clip(v2, 0.0, None)
    return np.sqrt(v2)

def sample_radii_lbp(n, rng):
    a = np.exp(-Rin / Rc)
    b = np.exp(-Rout / Rc)
    u = rng.uniform(0.0, 1.0, n)
    return -Rc * np.log(a - u * (a - b))

def Mdisc_eff_lbp():
    return Mdisc * (np.exp(-Rin / Rc) - np.exp(-Rout / Rc))


# PROFILO AD ANELLO

def surface_density_ring(R):
    Sigma0 = Mdisc / (np.pi * ((R_ring+DR_ring)**2 - (R_ring-DR_ring)**2))
    return np.where(np.abs(R - R_ring) < DR_ring, Sigma0, 0.0)

def v_phi_ring(R):
    return v_kepler(R)

def sample_radii_ring(n, rng):
    u = rng.uniform(0.0, 1.0, n)
    Rin2  = (R_ring - DR_ring)**2
    Rout2 = (R_ring + DR_ring)**2
    return np.sqrt(u * (Rout2 - Rin2) + Rin2)

def Mdisc_eff_ring():
    return Mdisc



